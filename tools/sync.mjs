#!/usr/bin/env node
// Generate each tool's global instruction file from the library.
//   node tools/sync.mjs [--only claude,codex] [--dry-run]   write (backs up changed files first)
//   node tools/sync.mjs --check                              compare only, exit 1 on drift
//   node tools/sync.mjs --restore <backup-dir> [--force]     put preimages back
// Target modes: import (one @-line per part), copy (parts joined), dir (each file matching `source` copied
// verbatim into the `path` directory, with the generated marker after its YAML frontmatter, or as a "#" comment
// on line 1 of a .toml file; generated files whose source is gone are orphans, reported by --check and
// retired by sync).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadConfig, normalize, sha256, charCount, writeAtomic, timestamp, expand, expandHome } from './lib.mjs';

const MARK = 'Generated by rules-as-code tools/sync.mjs';
const HEADER = (parts) => `<!-- ${MARK}; do not edit. Source: ${parts.join(' + ')} -->`;
// The library as an @-import prefix: the home directory spelled "~", forward slashes.
function importRoot(root) {
  const r = root.replace(/\\/g, '/');
  const home = expandHome('~').replace(/\\/g, '/');
  return r.toLowerCase().startsWith(home.toLowerCase() + '/') ? `~${r.slice(home.length)}` : r;
}
const FRONTMATTER = /^---\n[\s\S]*?\n---\n/;
// Generated = the marker comment right after the frontmatter, not the phrase anywhere in the body.
const MARK_RE = MARK.replace(/[.*+?^${}()|[\]\\/~]/g, '\\$&');
const GENERATED = new RegExp(`^---\\n[\\s\\S]*?\\n---\\n<!-- ${MARK_RE}`);
// A .toml file has no frontmatter: generated = the marker comment on line 1.
const TOML_HEADER = (parts) => `# ${MARK}; do not edit. Source: ${parts.join(' + ')}`;
const GENERATED_TOML = new RegExp(`^# ${MARK_RE}`);
const isToml = (name) => name.endsWith('.toml');
const isGenerated = (file) => (isToml(file) ? GENERATED_TOML : GENERATED).test(normalize(fs.readFileSync(file, 'utf8')));
// Keys every custom agent file must define (Codex: name, description, developer_instructions).
const TOML_REQUIRED = ['name', 'description', 'developer_instructions'];

// A dir target becomes one single-file target per source file ("<id>:<name>"), plus a "dir-missing" row
// when nothing matches and a "dir-orphan" row for each generated file left in the directory without a source.
export function expandTargets(targets, root = ROOT) {
  const out = [];
  for (const t0 of targets) {
    const t = t0.local ? t0 : { ...t0, path: expandHome(t0.path), ...(t0.retire && { retire: t0.retire.map((r) => expandHome(r)) }) };
    if (t.mode !== 'dir') { out.push(t); continue; }
    const files = expand(root, t.source);
    if (!files.length) out.push({ id: t.id, mode: 'dir-missing', path: t.path });
    const names = new Set();
    const ext = path.posix.extname(t.source) || '.md';
    for (const f of files) {
      const name = path.posix.basename(f);
      names.add(name);
      out.push({ id: `${t.id}:${name}`, mode: 'dir-file', parts: [f], path: path.join(t.path, name) });
    }
    // An empty source is reported, never treated as "delete everything generated".
    if (!files.length || !fs.existsSync(t.path)) continue;
    for (const name of fs.readdirSync(t.path).sort()) {
      const file = path.join(t.path, name);
      if (names.has(name) || !name.endsWith(ext) || !fs.statSync(file).isFile()) continue;
      if (isGenerated(file)) out.push({ id: `${t.id}:${name}`, mode: 'dir-orphan', path: file });
    }
  }
  return out;
}

export function build(target, root = ROOT) {
  if (target.mode === 'dir-file') {
    const src = normalize(fs.readFileSync(path.join(root, target.parts[0]), 'utf8'));
    if (isToml(target.parts[0])) return normalize(`${TOML_HEADER(target.parts)}\n${src}`);
    const m = src.match(FRONTMATTER);
    // No frontmatter: returned as is, and checkLimits refuses it.
    return m ? normalize(`${m[0]}${HEADER(target.parts)}\n${src.slice(m[0].length)}`) : src;
  }
  if (target.mode === 'import') {
    const lines = [HEADER(target.parts), '', ...target.parts.map((p) => `@${importRoot(root)}/${p}`)];
    return normalize(lines.join('\n'));
  }
  const body = target.parts
    .map((p) => normalize(fs.readFileSync(path.join(root, p), 'utf8')).trimEnd())
    .join('\n\n');
  const head = target.frontmatter ? `${target.frontmatter}\n\n` : '';
  return normalize(`${head}${HEADER(target.parts)}\n\n${body}`);
}

export function resolveTarget(target, root = ROOT) {
  return target.local ? path.join(root, target.path) : target.path;
}

export function checkLimits(target, content) {
  const problems = [];
  if (target.mode === 'dir-file' && isToml(target.parts[0])) {
    for (const key of TOML_REQUIRED) if (!new RegExp(`^${key}\\s*=`, 'm').test(content)) problems.push(`${target.id}: missing ${key}`);
  } else if (target.mode === 'dir-file' && !FRONTMATTER.test(content)) problems.push(`${target.id}: no YAML frontmatter on line 1`);
  if (target.maxChars && charCount(content) > target.maxChars)
    problems.push(`${target.id}: ${charCount(content)} chars > ${target.maxChars}`);
  if (target.maxBytes && Buffer.byteLength(content) > target.maxBytes)
    problems.push(`${target.id}: ${Buffer.byteLength(content)} bytes > ${target.maxBytes}`);
  return problems;
}

function selectTargets(cfg, only, root = ROOT) {
  if (!only) return expandTargets(cfg.targets, root);
  const ids = only.split(',');
  const unknown = ids.filter((id) => !cfg.targets.some((t) => t.id === id));
  if (unknown.length) throw new Error(`unknown target(s): ${unknown.join(', ')}`);
  return expandTargets(cfg.targets.filter((t) => ids.includes(t.id)), root);
}

export function check(root = ROOT, only) {
  const cfg = loadConfig(root);
  return selectTargets(cfg, only, root).map((t) => {
    if (t.mode === 'dir-missing' || t.mode === 'dir-orphan') {
      return { id: t.id, file: t.path, state: t.mode === 'dir-missing' ? 'missing_source' : 'orphan', chars: 0, bytes: 0, limits: [], retired_still_present: [] };
    }
    const want = build(t, root);
    const file = resolveTarget(t, root);
    const have = fs.existsSync(file) ? fs.readFileSync(file) : null;
    const limits = checkLimits(t, want);
    const state = have === null ? 'missing' : sha256(have) === sha256(Buffer.from(want)) ? 'in_sync' : 'drift';
    const retired = (t.retire || []).filter((f) => fs.existsSync(f));
    return { id: t.id, file, state, chars: charCount(want), bytes: Buffer.byteLength(want), limits, retired_still_present: retired };
  });
}

export function sync(root = ROOT, { only, dryRun = false, backupRoot } = {}) {
  const cfg = loadConfig(root);
  const targets = selectTargets(cfg, only, root);
  const runDir = path.join(expandHome(backupRoot || cfg.backupRoot), `prompt-sync-${timestamp()}`);
  // Validate every target before writing any, so a failure never leaves writes without a manifest.
  const problems = [];
  for (const t of targets) {
    if (t.mode === 'dir-missing' || t.mode === 'dir-orphan') continue;
    problems.push(...checkLimits(t, build(t, root)));
    const file = resolveTarget(t, root);
    if (t.mode === 'dir-file' && fs.existsSync(file) && !isGenerated(file)) problems.push(`${t.id}: ${file} exists and was not generated by sync; move it away first`);
  }
  if (problems.length) throw new Error(problems.join('; '));
  const entries = [];
  for (const t of targets) {
    if (t.mode === 'dir-missing') { entries.push({ id: t.id, path: t.path, action: 'missing_source' }); continue; }
    if (t.mode === 'dir-orphan') {
      const buf = fs.readFileSync(t.path);
      const backup = backupFile(runDir, t.path, buf, dryRun);
      if (!dryRun) fs.rmSync(t.path);
      entries.push({ id: t.id, path: t.path, action: 'retired', preimage_sha256: sha256(buf), backup });
      continue;
    }
    const want = build(t, root);
    const problems = checkLimits(t, want);
    if (problems.length) throw new Error(problems.join('; '));
    const file = resolveTarget(t, root);
    const exists = fs.existsSync(file);
    const before = exists ? fs.readFileSync(file) : null;
    if (before && sha256(before) === sha256(Buffer.from(want))) {
      entries.push({ id: t.id, path: file, action: 'unchanged' });
    } else {
      const entry = { id: t.id, path: file, action: exists ? 'replaced' : 'created', postimage_sha256: sha256(Buffer.from(want)) };
      if (before && !t.local) {
        entry.preimage_sha256 = sha256(before);
        entry.backup = backupFile(runDir, file, before, dryRun);
      }
      if (!dryRun) writeAtomic(file, want);
      entries.push(entry);
    }
    for (const old of t.retire || []) {
      if (!fs.existsSync(old)) continue;
      const buf = fs.readFileSync(old);
      const backup = backupFile(runDir, old, buf, dryRun);
      if (!dryRun) fs.rmSync(old);
      entries.push({ id: t.id, path: old, action: 'retired', preimage_sha256: sha256(buf), backup });
    }
  }
  const changed = entries.some((e) => e.action !== 'unchanged' && e.action !== 'missing_source');
  if (changed && !dryRun) {
    fs.mkdirSync(runDir, { recursive: true });
    fs.writeFileSync(path.join(runDir, 'manifest.json'), JSON.stringify({ schema: 'prompt_sync_manifest_v1', created_at: new Date().toISOString(), entries }, null, 2) + '\n');
  }
  return { runDir: changed ? runDir : null, entries, dryRun };
}

function backupFile(runDir, file, buf, dryRun) {
  const rel = file.replace(/\\/g, '/').replace(/^([A-Za-z]):\//, (_, d) => `drive-${d.toLowerCase()}/`);
  const dest = path.join(runDir, 'files', rel);
  if (!dryRun) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, buf);
    if (sha256(fs.readFileSync(dest)) !== sha256(buf)) throw new Error(`backup verification failed: ${file}`);
  }
  return path.relative(runDir, dest).replace(/\\/g, '/');
}

export function restore(runDir, { force = false } = {}) {
  const manifest = JSON.parse(fs.readFileSync(path.join(runDir, 'manifest.json'), 'utf8'));
  const results = [];
  for (const e of manifest.entries) {
    if (e.action === 'unchanged' || e.action === 'missing_source') continue;
    const current = fs.existsSync(e.path) ? sha256(fs.readFileSync(e.path)) : null;
    if (e.action === 'created') {
      if (current === e.postimage_sha256 || force) { if (current) fs.rmSync(e.path); results.push({ path: e.path, result: 'removed' }); }
      else results.push({ path: e.path, result: 'skipped_drift' });
      continue;
    }
    const buf = fs.readFileSync(path.join(runDir, e.backup));
    if (sha256(buf) !== e.preimage_sha256) { results.push({ path: e.path, result: 'backup_hash_mismatch' }); continue; }
    const expected = e.action === 'retired' ? null : e.postimage_sha256;
    if (current !== expected && !force) { results.push({ path: e.path, result: 'skipped_drift' }); continue; }
    writeAtomic(e.path, buf);
    results.push({ path: e.path, result: sha256(fs.readFileSync(e.path)) === e.preimage_sha256 ? 'restored' : 'restore_hash_mismatch' });
  }
  return results;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const val = (flag) => { const i = args.indexOf(flag); return i >= 0 ? args[i + 1] : undefined; };
  try {
    if (args.includes('--check')) {
      const rows = check(ROOT, val('--only'));
      console.log(JSON.stringify(rows, null, 2));
      process.exit(rows.some((r) => r.state !== 'in_sync' || r.limits.length || r.retired_still_present.length) ? 1 : 0);
    } else if (args.includes('--restore')) {
      const rows = restore(val('--restore'), { force: args.includes('--force') });
      console.log(JSON.stringify(rows, null, 2));
      process.exit(rows.every((r) => r.result === 'restored' || r.result === 'removed') ? 0 : 1);
    } else {
      console.log(JSON.stringify(sync(ROOT, { only: val('--only'), dryRun: args.includes('--dry-run') }), null, 2));
    }
  } catch (err) {
    console.error(err.message);
    process.exit(2);
  }
}
