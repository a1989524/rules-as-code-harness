import assert from 'node:assert/strict';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { ROOT, sha256 } from '../tools/lib.mjs';
import { lint } from '../tools/lint.mjs';
import { build, check, checkLimits, expandTargets, sync, restore } from '../tools/sync.mjs';

const temps = [];
function copyLibrary() {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'rules-as-code-'));
  temps.push(dir);
  for (const part of ['core.md', 'INDEX.md', 'adapters.json', 'rules', 'profiles', 'docs', 'evals', 'agents']) {
    if (existsSync(path.join(ROOT, part))) cpSync(path.join(ROOT, part), path.join(dir, part), { recursive: true });
  }
  return dir;
}
test.after(() => { for (const d of temps) rmSync(d, { recursive: true, force: true }); });

test('the real library passes lint', () => {
  assert.deepEqual(lint(ROOT).errors, []);
});

test('lint catches vendor terms, duplicates, budgets, CRLF and unrouted rules', () => {
  const dir = copyLibrary();
  const rule = path.join(dir, 'rules', 'git-hygiene.md');
  writeFileSync(rule, readFileSync(rule, 'utf8') + '\n- Edit files with apply_patch.\n');
  const dup = '- This sentence is long enough on purpose, so the duplicate check has to notice it in two different files.';
  writeFileSync(path.join(dir, 'rules', 'extra.md'), `# Extra\n\n${dup}\n`);
  writeFileSync(path.join(dir, 'rules', 'extra2.md'), `# Extra two\r\n\r\n${dup}\r\n` + 'x'.repeat(2700) + '\r\n');
  const { errors } = lint(dir);
  const text = errors.join('\n');
  assert.match(text, /git-hygiene\.md: tool-specific term "apply_patch"/);
  assert.match(text, /duplicate sentence/);
  assert.match(text, /extra2\.md: \d+ chars exceeds budget 2600/);
  assert.match(text, /extra2\.md: contains CR/);
  assert.match(text, /rules\/extra\.md appears 0 times/);
});

test('generated adapters respect tool limits', () => {
  const cfg = JSON.parse(readFileSync(path.join(ROOT, 'adapters.json'), 'utf8'));
  // Limits only, from what would be built: the test never reads the installed files in the home directory.
  for (const t of expandTargets(cfg.targets)) if (!t.mode.startsWith('dir-') || t.mode === 'dir-file') assert.deepEqual(checkLimits(t, build(t)), [], t.id);
  const claude = build(cfg.targets.find((t) => t.id === 'claude'));
  // Imports point at wherever the library lives, spelled with "~" when it sits under the home directory.
  const home = os.homedir().replace(/\\/g, '/');
  const root = ROOT.replace(/\\/g, '/');
  const lib = root.toLowerCase().startsWith(home.toLowerCase() + '/') ? `~${root.slice(home.length)}` : root;
  assert.ok(claude.startsWith(`<!-- Generated by rules-as-code tools/sync.mjs; do not edit. Source: core.md + profiles/claude-code.md + INDEX.md`));
  assert.ok(claude.includes(`\n\n@${lib}/core.md\n@${lib}/profiles/claude-code.md\n@${lib}/INDEX.md\n`));
  // Must-use rules ship in both the Claude (import) and Codex (copy) entries, and match hooks.mustRules.
  const must = cfg.hooks.mustRules;
  for (const rel of must) assert.ok(claude.includes(`@${lib}/${rel}\n`), `claude imports ${rel}`);
  const codex = cfg.targets.find((t) => t.id === 'codex');
  for (const rel of must) assert.ok(codex.parts.includes(rel), `codex copies ${rel}`);
  assert.ok(Buffer.byteLength(build(codex)) <= codex.maxBytes, 'codex entry fits its byte budget');
  const gemini = build(cfg.targets.find((t) => t.id === 'gemini'));
  assert.ok(gemini.startsWith('---\ntrigger:always_on\nalwaysApply: true\n---\n\n'));
  const copilot = build(cfg.targets.find((t) => t.id === 'copilot'));
  assert.match(copilot, /^<!-- .* -->\n\n# Core\n/);
});

test('sync backs up, writes, retires and restore puts preimages back', () => {
  const dir = copyLibrary();
  const out = path.join(dir, 'out');
  mkdirSync(out);
  const replaced = path.join(out, 'AGENTS.md');
  const retired = path.join(out, 'old.md');
  writeFileSync(replaced, 'old content\n');
  writeFileSync(retired, 'legacy rules\n');
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  cfg.targets = [
    { id: 'a', path: replaced, mode: 'copy', parts: ['core.md'], retire: [retired] },
    { id: 'b', path: path.join(out, 'new', 'CLAUDE.md'), mode: 'import', parts: ['core.md'] },
  ];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  const result = sync(dir, { backupRoot: path.join(dir, 'backups') });
  assert.deepEqual(result.entries.map((e) => e.action), ['replaced', 'retired', 'created']);
  assert.equal(existsSync(retired), false);
  assert.ok(check(dir).every((r) => r.state === 'in_sync'));
  const back = restore(result.runDir);
  assert.deepEqual(back.map((r) => r.result).sort(), ['removed', 'restored', 'restored']);
  assert.equal(readFileSync(replaced, 'utf8'), 'old content\n');
  assert.equal(readFileSync(retired, 'utf8'), 'legacy rules\n');
  assert.equal(existsSync(path.join(out, 'new', 'CLAUDE.md')), false);
});

test('a run that only creates files still writes a restorable manifest', () => {
  const dir = copyLibrary();
  const file = path.join(dir, 'fresh', 'CLAUDE.md');
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  cfg.targets = [{ id: 'a', path: file, mode: 'import', parts: ['core.md'] }];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  const { runDir } = sync(dir, { backupRoot: path.join(dir, 'backups') });
  assert.ok(existsSync(path.join(runDir, 'manifest.json')));
  assert.deepEqual(restore(runDir).map((r) => r.result), ['removed']);
  assert.equal(existsSync(file), false);
});

test('dir targets copy each file verbatim with the marker after its frontmatter, and retire orphans (2026-10-08)', () => {
  // Generated files are recognized by the marker right after the frontmatter, never by a phrase in the body.
  const dir = copyLibrary();
  const src = path.join(dir, 'agents', 'claude');
  rmSync(src, { recursive: true, force: true });
  mkdirSync(src, { recursive: true });
  writeFileSync(path.join(src, 'scout.md'), '---\nname: scout\ndescription: d\n---\n\nbody\n');
  writeFileSync(path.join(src, 'bare.md'), 'no frontmatter\n');
  const out = path.join(dir, 'out-agents');
  const backupRoot = path.join(dir, 'backups');
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  cfg.targets = [{ id: 'ag', mode: 'dir', source: 'agents/claude/*.md', path: out }];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  // A file without frontmatter would break the agent definition: sync refuses it.
  assert.throws(() => sync(dir, { backupRoot }), /ag:bare\.md: no YAML frontmatter/);
  rmSync(path.join(src, 'bare.md'));
  const first = sync(dir, { backupRoot });
  assert.deepEqual(first.entries.map((e) => [e.id, e.action]), [['ag:scout.md', 'created']]);
  const written = readFileSync(path.join(out, 'scout.md'), 'utf8');
  assert.ok(written.startsWith('---\nname: scout\ndescription: d\n---\n<!-- Generated by rules-as-code tools/sync.mjs'), 'frontmatter stays on line 1');
  assert.ok(written.endsWith('\n\nbody\n'));
  assert.deepEqual(check(dir).map((r) => [r.id, r.state]), [['ag:scout.md', 'in_sync']]);
  assert.deepEqual(check(dir, 'ag').map((r) => r.id), ['ag:scout.md'], '--only takes the dir id');
  writeFileSync(path.join(out, 'scout.md'), written.replace('body', 'edited by hand'));
  assert.equal(check(dir)[0].state, 'drift');
  sync(dir, { backupRoot });
  // A generated file whose source is gone is an orphan: reported, then retired; a user's own file is left alone.
  writeFileSync(path.join(out, 'mine.md'), '---\nname: mine\n---\nwritten by the user\n');
  rmSync(path.join(src, 'scout.md'));
  writeFileSync(path.join(src, 'runner.md'), '---\nname: runner\n---\nx\n');
  const rows = check(dir);
  assert.deepEqual(rows.map((r) => [r.id, r.state]).sort(), [['ag:runner.md', 'missing'], ['ag:scout.md', 'orphan']]);
  for (const r of rows) { assert.deepEqual(r.limits, []); assert.deepEqual(r.retired_still_present, []); }
  const second = sync(dir, { backupRoot });
  assert.deepEqual(second.entries.map((e) => [e.id, e.action]).sort(), [['ag:runner.md', 'created'], ['ag:scout.md', 'retired']]);
  assert.equal(existsSync(path.join(out, 'scout.md')), false);
  assert.equal(readFileSync(path.join(out, 'mine.md'), 'utf8'), '---\nname: mine\n---\nwritten by the user\n');
  assert.ok(check(dir).every((r) => r.state === 'in_sync'));
  assert.deepEqual(restore(second.runDir).map((r) => r.result).sort(), ['removed', 'restored']);
  assert.ok(existsSync(path.join(out, 'scout.md')));
  // An empty source is reported, not thrown, with the fields the CLI's exit code reads.
  rmSync(src, { recursive: true });
  const empty = check(dir).find((r) => r.state === 'missing_source');
  assert.ok(empty);
  assert.deepEqual(empty.limits, []);
  assert.deepEqual(empty.retired_still_present, []);
});

test('dir targets leave user files alone, validate before writing, and keep generated files when the source vanishes (review 2026-10-08)', () => {
  const dir = copyLibrary();
  const src = path.join(dir, 'agents', 'claude');
  rmSync(src, { recursive: true, force: true });
  mkdirSync(src, { recursive: true });
  writeFileSync(path.join(src, 'scout.md'), '---\nname: scout\n---\nx\n');
  const out = path.join(dir, 'out-agents');
  mkdirSync(out, { recursive: true });
  const backupRoot = path.join(dir, 'backups');
  // A user file that merely quotes the marker in its body is not an orphan.
  const quoting = '---\nname: mine\n---\nNote: the other files are Generated by rules-as-code tools/sync.mjs.\n';
  writeFileSync(path.join(out, 'mine.md'), quoting);
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  const first = path.join(dir, 'first.md');
  writeFileSync(first, 'before\n');
  cfg.targets = [{ id: 'a', path: first, mode: 'copy', parts: ['core.md'] }, { id: 'ag', mode: 'dir', source: 'agents/claude/*.md', path: out }];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  assert.deepEqual(check(dir).map((r) => r.id), ['a', 'ag:scout.md'], 'no orphan for the quoting file');
  // A same-name file the user wrote (no marker after its frontmatter) is not overwritten.
  writeFileSync(path.join(out, 'scout.md'), '---\nname: scout\n---\nthe user\'s own version\n');
  assert.throws(() => sync(dir, { backupRoot }), /ag:scout\.md: .*not generated/);
  // Validation runs before any write: the copy target listed first was not touched.
  assert.equal(readFileSync(first, 'utf8'), 'before\n');
  rmSync(path.join(out, 'scout.md'));
  sync(dir, { backupRoot });
  assert.equal(readFileSync(path.join(out, 'mine.md'), 'utf8'), quoting);
  // The source directory vanishing reports missing_source but does not wipe the generated files.
  rmSync(src, { recursive: true });
  assert.deepEqual(check(dir).filter((r) => r.id.startsWith('ag')).map((r) => r.state), ['missing_source']);
  const res = sync(dir, { backupRoot });
  assert.ok(existsSync(path.join(out, 'scout.md')));
  assert.deepEqual(res.entries.filter((e) => e.id.startsWith('ag')).map((e) => e.action), ['missing_source']);
});

test('restore refuses to overwrite files changed after sync', () => {
  const dir = copyLibrary();
  const file = path.join(dir, 'target.md');
  writeFileSync(file, 'before\n');
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  cfg.targets = [{ id: 'a', path: file, mode: 'copy', parts: ['core.md'] }];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  const { runDir } = sync(dir, { backupRoot: path.join(dir, 'backups') });
  writeFileSync(file, 'edited by user\n');
  assert.deepEqual(restore(runDir).map((r) => r.result), ['skipped_drift']);
  assert.equal(sha256(readFileSync(file)), sha256(Buffer.from('edited by user\n')));
});

test('dir targets also carry TOML agent files: marker on line 1, required keys checked, orphans by extension (2026-10-12)', () => {
  const dir = copyLibrary();
  const src = path.join(dir, 'agents', 'codex');
  rmSync(src, { recursive: true, force: true });
  mkdirSync(src, { recursive: true });
  const out = path.join(dir, 'out-codex');
  const backupRoot = path.join(dir, 'backups');
  const cfg = JSON.parse(readFileSync(path.join(dir, 'adapters.json'), 'utf8'));
  cfg.targets = [{ id: 'cx', mode: 'dir', source: 'agents/codex/*.toml', path: out }];
  writeFileSync(path.join(dir, 'adapters.json'), JSON.stringify(cfg));
  writeFileSync(path.join(src, 'bad.toml'), 'name = "bad"\n');
  assert.throws(() => sync(dir, { backupRoot }), /cx:bad\.toml: missing developer_instructions/);
  rmSync(path.join(src, 'bad.toml'));
  writeFileSync(path.join(src, 'scout.toml'), 'name = "scout"\ndescription = "inventory"\ndeveloper_instructions = """\nbody\n"""\n');
  sync(dir, { backupRoot });
  const written = readFileSync(path.join(out, 'scout.toml'), 'utf8');
  assert.match(written, /^# Generated by rules-as-code tools\/sync\.mjs; do not edit\. Source: agents\/codex\/scout\.toml\nname = "scout"\n/);
  assert.deepEqual(check(dir).map((r) => [r.id, r.state]), [['cx:scout.toml', 'in_sync']]);
  writeFileSync(path.join(out, 'mine.toml'), 'name = "mine"\n');
  rmSync(path.join(src, 'scout.toml'));
  writeFileSync(path.join(src, 'runner.toml'), 'name = "runner"\ndescription = "runs commands"\ndeveloper_instructions = "x"\n');
  assert.deepEqual(check(dir).map((r) => [r.id, r.state]).sort(), [['cx:runner.toml', 'missing'], ['cx:scout.toml', 'orphan']]);
  sync(dir, { backupRoot });
  assert.equal(existsSync(path.join(out, 'scout.toml')), false);
  assert.equal(readFileSync(path.join(out, 'mine.toml'), 'utf8'), 'name = "mine"\n', "a user's own file is left alone");
});
